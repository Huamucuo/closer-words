// Downloads subset fonts (only the glyphs the film uses) from Google Fonts into fonts/.
// Re-run whenever on-screen text changes: `npm run fonts`
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const FAMILIES = [
  { family: 'Noto Serif SC', axes: 'wght@500;700;900', cjk: true },
  { family: 'Noto Sans SC', axes: 'wght@400;500;700;900', cjk: true },
  { family: 'JetBrains Mono', axes: 'wght@500;800' },
  { family: 'Noto Serif', axes: 'ital,wght@1,400' },
];

const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const sources = [path.join(ROOT, 'promo.html'), ...walk(path.join(ROOT, 'src')).filter(f => f.endsWith('.js'))];
const used = new Set();
for (const f of sources) for (const ch of fs.readFileSync(f, 'utf8')) if (ch.codePointAt(0) > 126) used.add(ch);
let ascii = '';
for (let c = 32; c < 127; c++) ascii += String.fromCharCode(c);
const extra = '，。：；、？！“”‘’—…·（）《》％';
const cjkText = ascii + extra + [...used].join('');
const latinText = ascii + '’“”—…·';

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) if (f.endsWith('.woff2')) fs.unlinkSync(path.join(OUT, f));

const get = async (u, o, tries = 5) => {
  for (let i = 1; ; i++) {
    try { return await fetch(u, o); } catch (e) { if (i >= tries) throw e; await new Promise(r => setTimeout(r, 1500 * i)); }
  }
};

let css = '/* generated by tools/fetch-fonts.mjs — subset to the film\'s glyphs (SIL Open Font License) */\n';
for (const { family, axes, cjk } of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:${axes}&display=block&text=${encodeURIComponent(cjk ? cjkText : latinText)}`;
  const res = await get(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${family}: HTTP ${res.status}`);
  let block = await res.text();
  const urls = [...block.matchAll(/url\((https:[^)]+)\)/g)].map(m => m[1]);
  let i = 0;
  for (const u of urls) {
    const name = `${family.replace(/ /g, '')}-${i++}.woff2`;
    const buf = Buffer.from(await (await get(u, { headers: { 'User-Agent': UA } })).arrayBuffer());
    fs.writeFileSync(path.join(OUT, name), buf);
    block = block.replace(u, name);
    console.log(`${name}  ${(buf.length / 1024).toFixed(0)} KB`);
  }
  css += block;
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), css);
console.log(`fonts.css written — ${used.size} non-ASCII glyphs`);
